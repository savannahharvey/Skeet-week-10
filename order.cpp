#include "order.h"

// Standalone functions

// draw functions

/**************************************************************
* DRAW EFFECT
* **************************************************************/
void drawEffect(Effect* p)
{
   assert(p != nullptr);
   p->render();
}

/**************************************************************
* DRAW BULLET
* *************************************************************/
void drawBullet(Bullet* p)
{
   assert(p != nullptr);
   p->output();
}

/**************************************************************
* DRAW BIRD
* *************************************************************/
void drawBird(Bird* p)
{
   assert(p != nullptr);
   p->draw();
}

/**************************************************************
* DRAW GUN
* *************************************************************/
void drawGun(const Gun& gun)
{
   gun.display();
}

// move functions

/**************************************************************
* MOVE EFFECT
* **************************************************************/
void moveEffect(Effect* p)
{
   assert(p != nullptr);
   p->fly();
}

/**************************************************************
* MOVE BULLET
* *************************************************************/
void moveBullet(Bullet* p, std::list<Effect*>& effects)
{
   assert(p != nullptr);
   p->move(effects);
}

/**************************************************************
* MOVE BIRD
* *************************************************************/
void moveBird(Bird* p)
{
   assert(p != nullptr);
   p->advance();
}

// kill functions

/**************************************************************
* KILL BULLET
* *************************************************************/
void killBullet(Bullet* p)
{
   assert(p != nullptr);
   p->kill();
}

/**************************************************************
* KILL BIRD
* *************************************************************/
void killBird(Bird* p)
{
   assert(p != nullptr);
   p->kill();
}